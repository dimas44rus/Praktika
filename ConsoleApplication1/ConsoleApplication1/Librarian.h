#ifndef LIBRARIAN_H // Защита препроцессора от циклического подключения заголовочного файла
#define LIBRARIAN_H // Регистрация уникального имени макроса для текущего файла

#include <string> // Включение встроенного класса работы со строками std::string

class Librarian { // Объявление класса Librarian (Библиотекарь)
private: // Скрытые внутренние переменные класса
    std::string name; // Текстовое поле для хранения имени сотрудника

public: // Публичные функции класса, доступные извне
    Librarian(std::string n); // Прототип конструктора, принимающего имя библиотекаря

    std::string getName() const; // Прототип геттера для безопасного чтения имени сотрудника
    void greet() const; // Прототип метода вежливого приветствия пользователя
    void announceError(const std::string& message) const; // Прототип метода для сообщений о проблемах
    void confirmAction(const std::string& message) const; // Прототип метода для подтверждения успешных действий
};

#endif // LIBRARIAN_H // Конец условной сборки для текущего заголовочного файла
