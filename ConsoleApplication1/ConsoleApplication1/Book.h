#ifndef BOOK_H // Защита от повторного включения заголовочного файла при компиляции
#define BOOK_H // Определение уникальной метки макроса для этого файла

#include <string> // Подключение стандартной библиотеки работы со строками string

class Book { // Объявление класса Book (Книга)
private: // Закрытая секция: поля доступны только методам самого класса
    std::string title; // Переменная для хранения названия книги
    std::string author; // Переменная для хранения автора книги
    bool isAvailable; // Статус книги: true — на полке, false — на руках у читателя

public: // Открытая секция: методы доступны из любого места программы
    Book(std::string t, std::string a); // Прототип конструктора для создания книги с параметрами

    std::string getTitle() const; // Прототип геттера названия книги (const гарантирует неизменяемость полей)
    std::string getAuthor() const; // Прототип геттера автора книги
    bool getIsAvailable() const; // Прототип геттера статуса доступности книги
    void setIsAvailable(bool status); // Прототип сеттера для изменения статуса доступности книги

    void printInfo() const; // Прототип метода вывода информации о книге в консоль
}; // Точка с запятой обязательна после закрытия тела класса

#endif // BOOK_H // Конец директивы препроцессора #ifndef
