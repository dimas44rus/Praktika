#ifndef LIBRARY_H // Защита от повторного подключения заголовочного файла в другие компоненты
#define LIBRARY_H // Объявление уникальной метки препроцессора для этого файла

#include <string> // Включение библиотеки строк std::string
#include <vector> // Включение стандартного динамического массива (контейнера vector) из STL
#include "Book.h" // Подключение класса Книги, так как библиотека оперирует книгами
#include "Librarian.h" // Подключение класса Библиотекаря, так как библиотека нанимает сотрудника

class Library { // Объявление комплексного класса Library (Библиотека)
private: // Скрытые внутренние свойства и утилиты филиала
    std::string name; // Строка для хранения названия филиала библиотеки
    Librarian librarian; // Объект привязанного к филиалу библиотекаря (композиция объектов)
    std::vector<Book> catalog; // Контейнер-каталог, хранящий список всех книг этого филиала

    // Приватный метод-помощник: переводит строку в нижний регистр для удобного поиска
    std::string toLower(std::string str) const;

public: // Публичные интерфейсные методы библиотеки
    // Конструктор: принимает название библиотеки, объект библиотекаря и вектор книг
    Library(std::string n, Librarian l, std::vector<Book> books);

    std::string getName() const; // Прототип геттера названия филиала библиотеки
    void showInfo() const; // Прототип метода отображения карточки филиала
    void search(const std::string& query) const; // Прототип метода поиска книги в каталоге
    void borrowBook(const std::string& title); // Прототип метода выдачи книги читателю
    void returnBook(const std::string& title); // Прототип метода приема возвращаемой книги
};

#endif // LIBRARY_H // Завершение защиты препроцессора #ifndef
