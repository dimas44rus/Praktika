#include "Storage.h" // Подключение заголовочного файла класса хранилища для реализации его логики.
#include <fstream> // Подключение библиотеки файловых потоков для чтения (ifstream) и записи (ofstream).
#include <iostream> // Подключение базового ввода-вывода, если понадобятся потоки консоли.

std::vector<CitizenRequest> Storage::loadRequests() { // Реализация статического метода загрузки всех обращений.
    std::vector<CitizenRequest> requests; // Создаем локальный пустой вектор, который заполним объектами и вернем из функции.
    std::ifstream file("database.txt"); // Открываем файловый поток на чтение текстового файла базы данных с именем database.txt.
    if (!file.is_open()) return requests; // Проверяем: если файл еще не создан или поврежден, сразу возвращаем пустой вектор.

    int id; // Временная переменная для пошагового считывания идентификатора обращения.
    std::string name, text, answer; // Временные строки для считывания имени, текста жалобы и текста ответа сотрудника.
    bool isResolved; // Временный логический флаг для считывания статуса из текстового файла.

    while (file >> id) { // Запускаем цикл, который работает до тех пор, пока удается считать очередное числовое значение ID.
        file.ignore(); // Очищаем символ перевода строки из буфера потока после считывания числа методом >>.
        std::getline(file, name); // Считываем всю текстовую строку с ФИО гражданина до символа переноса строки.
        std::getline(file, text); // Считываем всю текстовую строку с описанием проблемы гражданина.
        std::getline(file, answer); // Считываем текстовую строку с ответом, если он был ранее добавлен сотрудником.
        file >> isResolved; // Считываем логическое значение статуса (0 или 1) из файла в переменную.
        file.ignore(); // Повторно очищаем остаточный перенос строки в конце блока данных одного обращения.

        CitizenRequest req(id, name, text); // Создаем временный объект обращения с помощью конструктора.
        if (isResolved) { // Если считанный из файла флаг равен true (1), то нужно прикрепить ответ.
            req.setAnswer(answer); // Принудительно вызываем метод setAnswer, который запишет ответ и выставит статус true объекту.
        } // Конец проверки статуса.
        requests.push_back(req); // Добавляем полностью сформированный объект обращения в конец результирующего вектора.
    } // Конец цикла чтения файла.
    file.close(); // Вручную закрываем файловый поток после завершения чтения всех данных для освобождения дескриптора.
    return requests; // Возвращаем заполненный вектор со всеми объектами обратно в вызывающий программный код.
} // Конец реализации метода loadRequests.

void Storage::saveRequests(const std::vector<CitizenRequest>& requests) { // Реализация метода полной перезаписи базы данных из вектора в файл.
    std::ofstream file("database.txt"); // Создаем поток вывода и открываем (или очищаем) файл database.txt для записи.
    for (const auto& req : requests) { // Запускаем цикл range-based for по всем элементам переданного вектора обращений.
        file << req.getId() << "\n" // Записываем ID обращения на первую строчку блока данных.
            << req.getCitizenName() << "\n" // Записываем имя гражданина на вторую строчку блока.
            << req.getText() << "\n" // Записываем текст обращения на третью строчку блока.
            << req.getAnswer() << "\n" // Записываем текущий ответ сотрудника на четвертую строчку блока.
            << req.getStatus() << "\n"; // Записываем статус в виде 0 или 1 на пятую строчку блока и переходим дальше.
    } // Конец цикла прохода по вектору.
    file.close(); // Вручную закрываем файл, сохраняя все внесенные изменения на жесткий диск.
} // Конец реализации метода saveRequests.

int Storage::getNextId() { // Реализация метода расчета свободного идентификатора для нового обращения.
    auto requests = loadRequests(); // Вызываем метод loadRequests для считывания актуального списка текущих обращений.
    if (requests.empty()) return 1; // Если база пустая и обращений нет, то первый свободный ID гарантированно равен 1.
    return requests.back().getId() + 1; // Если обращения есть, берем ID самого последнего элемента через back() и прибавляем к нему 1.
} // Конец реализации метода getNextId.
