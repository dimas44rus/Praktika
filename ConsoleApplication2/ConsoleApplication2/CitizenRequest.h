#include <string> // Подключение стандартной библиотеки для работы со строками типа std::string.

class CitizenRequest { // Объявление класса CitizenRequest, который описывает модель обращения гражданина.
private: // Спецификатор доступа private ограничивает прямой доступ к полям из внешнего кода (сокрытие данных).
    int id; // Переменная для хранения уникального идентификационного номера обращения.
    std::string citizenName; // Строковая переменная для хранения ФИО гражданина, создавшего обращение.
    std::string text; // Строковая переменная для хранения основного текста самого обращения.
    std::string answer; // Строковая переменная для хранения текста ответа сотрудника ведомства.
    bool isResolved; // Логический флаг, указывающий, решено ли обращение (true) или находится в обработке (false).

public: // Спецификатор доступа public открывает методы для взаимодействия с объектом извне (инкапсуляция).
    CitizenRequest(int id, const std::string& citizenName, const std::string& text); // Объявление конструктора класса для инициализации нового объекта обращения.
    int getId() const; // Константный метод-геттер для получения уникального идентификатора (ID) обращения.
    std::string getCitizenName() const; // Константный метод-геттер для получения ФИО автора данного обращения.
    std::string getText() const; // Константный метод-геттер для получения содержимого текста обращения.
    std::string getAnswer() const; // Константный метод-геттер для получения текста ответа сотрудника.
    bool getStatus() const; // Константный метод-геттер для проверки текущего статуса решения проблемы.
    void setAnswer(const std::string& officialAnswer); // Метод-сеттер для записи ответа сотрудника и закрытия обращения.
}; // Закрывающая фигурная скобка описания структуры класса с обязательной точкой с запятой.

#endif // Завершение блока условной компиляции защиты заголовочного файла #ifndef.
